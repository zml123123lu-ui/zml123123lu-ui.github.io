import test from 'node:test';
import assert from 'node:assert/strict';
import { cleanEntry,saveManagedContent,readDashboard } from './content-manager.mjs';
import { mkdtemp,mkdir,writeFile,readFile,rm,cp } from 'node:fs/promises';
import path from 'node:path';
import {tmpdir} from 'node:os';

test('管理表单拒绝危险网址、非法评分和分区',()=>{
 assert.throws(()=>cleanEntry('accounts',{title:'账号',url:'javascript:alert(1)'}));
 assert.throws(()=>cleanEntry('books',{title:'书',status:'在读',rating:6}));
 assert.throws(()=>cleanEntry('posts',{title:'文',pubDate:'2026-11-06',category:'不存在'}));
 assert.throws(()=>cleanEntry('constructor',{}));
 assert.equal(cleanEntry('books',{title:'书',status:'读完',rating:5}).rating,5);
 assert.equal(cleanEntry('books',{title:'书',status:'读完',cover:'/book-covers/3300013610.jpg'}).cover,'/book-covers/3300013610.jpg');
 for(const cover of ['/book-covers/../secret.jpg','//example.com/cover.jpg','/book-covers/a.svg'])assert.throws(()=>cleanEntry('books',{title:'书',status:'读完',cover}));
 assert.equal(cleanEntry('films',{title:'电影',status:'看过',cover:'/film-posters/film-1.jpg'}).group,'电影');
 assert.equal(cleanEntry('films',{title:'番',status:'看过',group:'番剧'}).group,'番剧');
 assert.throws(()=>cleanEntry('films',{title:'影片',status:'看过',group:'其他'}));
 assert.throws(()=>cleanEntry('films',{title:'影片',status:'看过',cover:'/film-posters/../private.jpg'}));
 assert.equal(cleanEntry('works',{title:'成果',url:'/works/vibe-coding/'}).url,'/works/vibe-coding/');
 for(const url of ['/works/../secret/','//example.com/','/manage/'])assert.throws(()=>cleanEntry('works',{title:'成果',url}));
});
test('数据保存成功才更换页面，失败时恢复原始文件，草稿标志保留',async()=>{
 const root=await mkdtemp(path.join(tmpdir(),'jianji-content-test-'));
 try{
 await mkdir(path.join(root,'src/data'),{recursive:true});await mkdir(path.join(root,'src/content/posts'),{recursive:true});await mkdir(path.join(root,'dist'));
 const catalog=JSON.stringify({accounts:[],books:[],films:[],works:[]});await writeFile(path.join(root,'src/data/catalog.json'),catalog);await writeFile(path.join(root,'dist/index.html'),'old');
 await cp(new URL('../src/data/site-text.json',import.meta.url),path.join(root,'src/data/site-text.json'));
 for(const directory of ['pages','music']) await cp(new URL(`../src/content/${directory}`,import.meta.url),path.join(root,`src/content/${directory}`),{recursive:true});
 const build=async output=>{await mkdir(output);await writeFile(path.join(output,'index.html'),'new')};
 const fixture={kind:'books',entry:{id:'fixture',title:'仅测试书籍',status:'读完',rating:4,note:'<script>作为普通文字</script>'}};
 await assert.rejects(saveManagedContent(fixture,{root,build:async()=>{throw Error('build failed')}}));
 assert.equal(await readFile(path.join(root,'src/data/catalog.json'),'utf8'),catalog);
 assert.equal(await readFile(path.join(root,'dist/index.html'),'utf8'),'old');
 await saveManagedContent(fixture,{root,build});assert.equal((await readDashboard(root)).books[0].title,'仅测试书籍');
 await saveManagedContent({kind:'posts',entry:{id:'fixture-post',title:'仅测试草稿',category:'随笔',pubDate:'2026-11-06',draft:true,body:'正文',tags:'测试,草稿'}},{root,build});
 const draft=(await readDashboard(root)).posts[0];assert.equal(draft.draft,true);assert.equal(draft.body.trim(),'正文');
 await assert.rejects(saveManagedContent({kind:'posts',entry:{id:'../../invalid'},operation:'remove'},{root,build}),/标识/);
 await saveManagedContent({...fixture,operation:'remove'},{root,build});assert.equal((await readDashboard(root)).books.length,0);
 const initial=await readDashboard(root), copyBefore=await readFile(path.join(root,'src/data/site-text.json'),'utf8');
 const patch={kind:'site',entry:{id:'home',changes:{quote:'测试 <script>文字</script>'}}};
 await assert.rejects(saveManagedContent(patch,{root,build:async()=>{throw Error('build failed')}}));
 assert.equal(await readFile(path.join(root,'src/data/site-text.json'),'utf8'),copyBefore);
 await saveManagedContent(patch,{root,build});
 const home=(await readDashboard(root)).site.find(item=>item.id==='home');
 assert.equal(home.quote,'测试 <script>文字</script>');assert.equal(home.highlight,initial.site.find(item=>item.id==='home').highlight);
 await assert.rejects(saveManagedContent({kind:'site',entry:{id:'home'},operation:'remove'},{root,build}));
 await assert.rejects(saveManagedContent({kind:'site',entry:{id:'unknown',changes:{quote:'x'}}},{root,build}));
 await assert.rejects(saveManagedContent({kind:'site',entry:{id:'music',changes:{tracks:[]}}},{root,build}));
 await assert.rejects(saveManagedContent({kind:'site',entry:{id:'identity',changes:{email:'bad\nemail'}}},{root,build}));
 const musicFile=path.join(root,'src/content/music/listening.md');
 const yaml=(await import('js-yaml')).default, oldMusic=yaml.load((await readFile(musicFile,'utf8')).match(/^---\n([\s\S]*?)\n---/)[1]);
 await saveManagedContent({kind:'site',entry:{id:'music',changes:{intro:'测试音乐介绍'}}},{root,build});
 const newMusic=yaml.load((await readFile(musicFile,'utf8')).match(/^---\n([\s\S]*?)\n---/)[1]);
 assert.deepEqual(newMusic.tracks,oldMusic.tracks);assert.deepEqual(newMusic.playlists,oldMusic.playlists);assert.equal(newMusic.intro,'测试音乐介绍');
 await saveManagedContent({kind:'site',entry:{id:'about',changes:{body:'## 自己的介绍\n\n正文'}}},{root,build});
 assert.equal((await readDashboard(root)).site.find(item=>item.id==='about').body.trim(),'## 自己的介绍\n\n正文');
 await saveManagedContent({kind:'posts',entry:{id:'fixture-post',changes:{title:'记录1',category:'开发',subtitle:'搭个网站'}}},{root,build});
 const updated=(await readDashboard(root)).posts[0];assert.equal(updated.title,'记录1');assert.equal(updated.subtitle,'搭个网站');assert.equal(updated.body.trim(),'正文');assert.equal(updated.draft,true);
 const postFile=path.join(root,'src/content/posts/fixture-post.md'), originalPost=await readFile(postFile,'utf8');
 const beforeDelete=await readFile(path.join(root,'dist/index.html'),'utf8');
 const removePost={kind:'posts',entry:{id:'fixture-post'},operation:'remove'};
 await assert.rejects(saveManagedContent(removePost,{root,build:async()=>{throw Error('delete build failed')}}));
 assert.equal(await readFile(postFile,'utf8'),originalPost);
 assert.equal(await readFile(path.join(root,'dist/index.html'),'utf8'),beforeDelete);
 await saveManagedContent(removePost,{root,build});
 assert.equal((await readDashboard(root)).posts.length,0);
 await assert.rejects(readFile(postFile),{code:'ENOENT'});
 await assert.rejects(saveManagedContent(removePost,{root,build}),/不存在/);
 }finally{await rm(root,{recursive:true,force:true})}
});
